update public.services as s
set
  description = c.description,
  duration_minutes = c.duration_minutes,
  price_cents = c.price_cents,
  is_active = c.is_active,
  sort_order = c.sort_order
from _service_catalog_seed as c
where s.name = c.name;

insert into public.services
  (name, description, duration_minutes, price_cents, is_active, sort_order)
select
  c.name, c.description, c.duration_minutes, c.price_cents, c.is_active,
  c.sort_order
from _service_catalog_seed as c
where not exists (
  select 1 from public.services as s where s.name = c.name
);

