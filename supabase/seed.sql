-- Стартовые данные, обязательные для работы приложения.
--
-- business_settings — синглтон-строка (id = 1), без неё бот и админ-панель
-- не смогут прочитать часовой пояс и остальные настройки организации.
-- Значения по умолчанию соответствуют разделу 7.1 технического задания;
-- администратор может изменить их позже через /admin/settings.
--
-- Расписание и блокировки намеренно не заполняются здесь: это реальные
-- бизнес-данные, которые должен ввести администратор через панель, а не
-- тестовые данные, случайно оставшиеся в проекте.
--
-- Каталог услуг ниже — демонстрационные данные ниши "салон красоты и
-- барбершоп" для нового/демонстрационного окружения, чтобы бот сразу мог
-- показать раздел записи. Блок идемпотентен (можно применять повторно) и
-- никогда не удаляет и не деактивирует чужие услуги: он обновляет по
-- точному совпадению name уже существующие строки и добавляет только
-- отсутствующие. Собственные услуги администратора, добавленные позже
-- через панель, этим блоком не затрагиваются.

