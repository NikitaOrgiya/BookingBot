-- Демонстрационный каталог услуг ("салон красоты и барбершоп").
--
-- В public.services нет уникального ограничения на name (только на id,
-- значение которого генерируется автоматически и заранее неизвестно),
-- поэтому здесь нет естественного ключа для INSERT ... ON CONFLICT.
-- Вместо этого используется явная транзакция:
--   1) UPDATE уже существующих строк по точному совпадению name;
--   2) INSERT только тех строк каталога, для которых совпадения по name
--      не нашлось (WHERE NOT EXISTS).
-- Повторный запуск ничего не дублирует и не удаляет: шаг (1) на второй
-- прогон обновит те же строки теми же значениями, шаг (2) не найдёт
-- новых имён для вставки. Услуги, отсутствующие в каталоге ниже (в том
-- числе добавленные администратором вручную), не изменяются и не
-- деактивируются.
