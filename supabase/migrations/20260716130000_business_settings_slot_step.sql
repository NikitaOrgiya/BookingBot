-- Этап 2. Шаг сетки слотов доступности.
--
-- В репозитории (ТЗ, миграции, seed) шаг сетки слотов нигде не был задан.
-- Чтобы не оставлять необъяснённое магическое число в коде функции
-- get_available_slots, шаг вынесен в настройку организации со значением
-- по умолчанию 15 минут — это документированная константа-настройка, а не
-- зашитое в SQL число. Администратор при необходимости сможет изменить шаг
-- (например, на 30 минут) через панель настроек, не трогая функции.
--
-- Не переписывает уже применённую 20260716100300_business_settings.sql —
-- только добавляет новый столбец поверх текущего состояния схемы. Значение
-- по умолчанию (15) автоматически проставляется в уже существующую
-- строку-синглтон.

alter table public.business_settings
  add column slot_step_minutes integer not null default 15;

alter table public.business_settings
  add constraint business_settings_slot_step_range
    check (slot_step_minutes between 5 and 120);
